CREATE TABLE system_settings (
  id integer PRIMARY KEY CHECK (id = 1),
  maintenance boolean NOT NULL DEFAULT false,
  maintenance_message varchar(500),
  revision integer NOT NULL DEFAULT 1 CHECK (revision > 0),
  announcement_cache_version bigint NOT NULL DEFAULT 0 CHECK (announcement_cache_version >= 0),
  CHECK (maintenance OR maintenance_message IS NULL)
);
INSERT INTO system_settings (id) VALUES (1);

CREATE TYPE "SystemAuditAction" AS ENUM ('maintenance', 'announcement_publish', 'announcement_unpublish', 'announcement_cache_invalidate', 'sessions_revoke');
CREATE TABLE system_audit_entries (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id uuid NOT NULL REFERENCES auth_users(id) ON DELETE RESTRICT ON UPDATE CASCADE,
  action "SystemAuditAction" NOT NULL,
  target_id uuid,
  reason varchar(500) NOT NULL CHECK (length(trim(reason)) >= 10),
  details jsonb NOT NULL CHECK (jsonb_typeof(details) = 'object'),
  created_at timestamptz(3) NOT NULL DEFAULT now()
);
