CREATE TYPE "NotificationKind" AS ENUM ('provider_decision', 'agreement', 'payment', 'completion', 'arbitration', 'support');
CREATE TABLE notifications (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  recipient_id uuid NOT NULL REFERENCES auth_users(id) ON DELETE CASCADE ON UPDATE CASCADE,
  kind "NotificationKind" NOT NULL,
  source_id uuid NOT NULL,
  event_key varchar(80) NOT NULL,
  created_at timestamptz(3) NOT NULL DEFAULT now(),
  read_at timestamptz(3),
  UNIQUE(recipient_id, kind, event_key)
);
CREATE INDEX notifications_recipient_id_id_idx ON notifications(recipient_id,id);
CREATE INDEX notifications_unread_idx ON notifications(recipient_id) WHERE read_at IS NULL;

CREATE TABLE notification_preferences (
  user_id uuid PRIMARY KEY REFERENCES auth_users(id) ON DELETE CASCADE ON UPDATE CASCADE,
  booking_reminder_email boolean NOT NULL DEFAULT true,
  revision integer NOT NULL DEFAULT 1 CHECK (revision > 0)
);
