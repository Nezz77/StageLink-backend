CREATE TYPE "SupportStatus" AS ENUM ('open', 'resolved');
CREATE TYPE "SupportEntryKind" AS ENUM ('reply', 'note', 'status', 'assignment');
CREATE TABLE support_cases (
  id uuid PRIMARY KEY,
  owner_id uuid NOT NULL REFERENCES auth_users(id) ON DELETE RESTRICT ON UPDATE CASCADE,
  booking_id uuid REFERENCES bookings(id) ON DELETE RESTRICT ON UPDATE CASCADE,
  assignee_id uuid REFERENCES auth_users(id) ON DELETE RESTRICT ON UPDATE CASCADE,
  request_key uuid NOT NULL,
  subject varchar(140) NOT NULL CHECK (length(trim(subject)) >= 3),
  body varchar(2000) NOT NULL CHECK (length(trim(body)) >= 20),
  status "SupportStatus" NOT NULL DEFAULT 'open',
  revision integer NOT NULL DEFAULT 1 CHECK (revision > 0),
  created_at timestamptz(3) NOT NULL DEFAULT now(),
  UNIQUE (owner_id, request_key)
);
CREATE INDEX support_cases_owner_id_id_idx ON support_cases(owner_id,id);
CREATE INDEX support_cases_status_id_idx ON support_cases(status,id);
CREATE TABLE support_entries (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  case_id uuid NOT NULL REFERENCES support_cases(id) ON DELETE CASCADE ON UPDATE CASCADE,
  actor_id uuid NOT NULL REFERENCES auth_users(id) ON DELETE RESTRICT ON UPDATE CASCADE,
  request_key uuid,
  kind "SupportEntryKind" NOT NULL,
  staff boolean NOT NULL,
  body varchar(2000) NOT NULL CHECK (length(trim(body)) > 0),
  revision integer,
  assignee_id uuid REFERENCES auth_users(id) ON DELETE RESTRICT ON UPDATE CASCADE,
  status "SupportStatus",
  created_at timestamptz(3) NOT NULL DEFAULT now(),
  UNIQUE (case_id, actor_id, request_key),
  UNIQUE (case_id, revision),
  CHECK (kind = 'reply' OR staff),
  CHECK ((kind IN ('assignment','status')) = (revision IS NOT NULL)),
  CHECK ((kind = 'status') = (status IS NOT NULL)),
  CHECK (kind = 'assignment' OR assignee_id IS NULL)
);
CREATE INDEX support_entries_case_id_id_idx ON support_entries(case_id,id);

CREATE TABLE support_attachments (
  case_id uuid NOT NULL REFERENCES support_cases(id) ON DELETE CASCADE ON UPDATE CASCADE,
  asset_id uuid NOT NULL REFERENCES assets(id) ON DELETE RESTRICT ON UPDATE CASCADE,
  position integer NOT NULL CHECK (position BETWEEN 0 AND 4),
  PRIMARY KEY(case_id,asset_id),
  UNIQUE(case_id,position)
);
CREATE INDEX support_attachments_asset_id_idx ON support_attachments(asset_id);
ALTER TABLE assets DROP CONSTRAINT assets_purpose_check;
ALTER TABLE assets ADD CONSTRAINT assets_purpose_check
  CHECK (purpose IN ('avatar', 'portfolio', 'equipment', 'evidence', 'chat', 'review', 'inspection', 'verification', 'support'));
